package com.skillmap.api.presentation.controller;

import com.jayway.jsonpath.JsonPath;
import com.skillmap.api.infrastructure.security.BCryptPasswordHasher;
import com.skillmap.api.support.TestAuth;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;

import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.not;
import static org.hamcrest.Matchers.nullValue;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Una base de antes de user_skills.updated_at (como la de una instalación anterior, con progreso guardado) sigue
 * funcionando: al arrancar se agrega la columna y las filas que ya había reciben la fecha de alta de su cuenta (la más
 * antigua posible, no una inventada); lo que se cambie después lleva la fecha del cambio.
 */
@SpringBootTest(properties = {
        "skillmap.home=${java.io.tmpdir}/skillmap-legacy-user-skills-test",
        "skillmap.desktop.open-browser=false",
        "jobs.sync.on-first-start=false",
        "jobs.sync.cron=-",
        "jobs.remotive.base-url=http://127.0.0.1:9",
        "jobs.arbeitnow.base-url=http://127.0.0.1:9",
        "skillmap.ai.remote-url=http://127.0.0.1:9",
        "skillmap.sync.remotive.enabled=false",
        "spring.jpa.show-sql=false",
        "GEMINI_API_KEY="
})
@AutoConfigureMockMvc
class LegacyUserSkillsTableTest {

    private static final String URL = "jdbc:h2:mem:skillmap-legacy-user-skills-test;DB_CLOSE_DELAY=-1";
    private static final String EMAIL = "progreso-antiguo@test.local";
    private static final String PASSWORD = "Clave-De-Antes-123";
    private static final String CREATED_AT = "2025-01-15T10:00:00Z";

    @Autowired
    MockMvc mvc;

    /**
     * Antes de crear el contexto: users y user_skills tal como las dejaba la versión anterior (sin updated_at), con
     * una cuenta que tenía React (id 1 del seed) dominada y TypeScript (id 2) en aprendizaje.
     */
    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        try (Connection connection = DriverManager.getConnection(URL, "sa", "");
             Statement statement = connection.createStatement()) {
            statement.execute("create table users (id bigint generated by default as identity, "
                    + "created_at timestamp(6) with time zone not null, email varchar(254) not null, "
                    + "name varchar(60) not null, password_hash varchar(100) not null, primary key (id), "
                    + "constraint uk_users_email unique (email))");
            statement.execute("create table user_skills (id bigint generated by default as identity, "
                    + "skill_id bigint not null, status varchar(255) not null, user_id bigint not null, primary key (id), "
                    + "constraint uk_user_skills_user_skill unique (user_id, skill_id))");
            try (PreparedStatement insert = connection.prepareStatement(
                    "insert into users (created_at, email, name, password_hash) values (?, ?, ?, ?)")) {
                insert.setTimestamp(1, Timestamp.from(Instant.parse(CREATED_AT)));
                insert.setString(2, EMAIL);
                insert.setString(3, "Progreso Antiguo");
                insert.setString(4, new BCryptPasswordHasher().hash(PASSWORD));
                insert.executeUpdate();
            }
            statement.execute("insert into user_skills (user_id, skill_id, status) values "
                    + "((select id from users where email = '" + EMAIL + "'), 1, 'MASTERED'), "
                    + "((select id from users where email = '" + EMAIL + "'), 2, 'IN_PROGRESS')");
        }
        registry.add("spring.datasource.url", () -> URL);
    }

    @Test
    void existingProgressGetsTheAccountCreationDate() throws Exception {
        try (Connection connection = DriverManager.getConnection(URL, "sa", "");
             Statement statement = connection.createStatement();
             ResultSet rows = statement.executeQuery("select count(*), count(updated_at) from user_skills")) {
            rows.next();
            assertThat(rows.getInt(1)).isEqualTo(2);
            assertThat(rows.getInt(2)).as("ninguna fila queda sin fecha").isEqualTo(2);
        }

        String token = login();
        mvc.perform(get("/api/skills/1").with(TestAuth.bearer(token)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("MASTERED"))
                .andExpect(jsonPath("$.statusUpdatedAt").value(CREATED_AT));
        mvc.perform(get("/api/skills/2").with(TestAuth.bearer(token)))
                .andExpect(jsonPath("$.status").value("IN_PROGRESS"))
                .andExpect(jsonPath("$.statusUpdatedAt").value(CREATED_AT));
    }

    @Test
    void changesAfterTheMigrationGetTheirOwnDate() throws Exception {
        String token = login();
        mvc.perform(put("/api/skills/3/status").with(TestAuth.bearer(token))
                        .contentType(MediaType.APPLICATION_JSON).content("{\"status\":\"IN_PROGRESS\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.statusUpdatedAt", not(nullValue())))
                .andExpect(jsonPath("$.statusUpdatedAt", not(CREATED_AT)));
    }

    private String login() throws Exception {
        return JsonPath.read(mvc.perform(post("/api/auth/login").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"" + EMAIL + "\",\"password\":\"" + PASSWORD + "\"}"))
                .andExpect(status().isOk())
                .andReturn().getResponse().getContentAsString(), "$.token");
    }
}
