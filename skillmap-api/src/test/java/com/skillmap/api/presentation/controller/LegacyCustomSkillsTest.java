package com.skillmap.api.presentation.controller;

import com.jayway.jsonpath.JsonPath;
import com.skillmap.api.domain.port.JobSkillExtractor;
import com.skillmap.api.support.TestAuth;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.mock.mockito.MockBean;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.hasSize;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Migración: una tabla skills de la versión anterior (sin owner_id ni custom_goal_id) sigue funcionando. Al arrancar se
 * agregan las columnas, las filas de antes quedan como catálogo (sin dueño, con su demanda) y ya se pueden crear
 * habilidades propias.
 */
@SpringBootTest(properties = {
        "skillmap.home=${java.io.tmpdir}/skillmap-legacy-custom-skills-test",
        "skillmap.desktop.open-browser=false",
        "jobs.sync.on-first-start=false",
        "jobs.sync.cron=-",
        "jobs.remotive.base-url=http://127.0.0.1:9",
        "jobs.arbeitnow.base-url=http://127.0.0.1:9",
        "skillmap.ai.remote-url=http://127.0.0.1:9",
        "skillmap.sync.remotive.enabled=false",
        "skillmap.sync.arbeitnow.enabled=false",
        "spring.jpa.show-sql=false",
        "GEMINI_API_KEY="
})
@AutoConfigureMockMvc
class LegacyCustomSkillsTest {

    private static final String URL = "jdbc:h2:mem:skillmap-legacy-custom-skills-test;DB_CLOSE_DELAY=-1";

    @Autowired
    MockMvc mvc;

    @Autowired
    JdbcTemplate jdbc;

    @MockBean
    JobSkillExtractor extractor;

    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        try (Connection connection = DriverManager.getConnection(URL, "sa", "");
             Statement statement = connection.createStatement()) {
            statement.execute("create table skills (id bigint generated by default as identity, "
                    + "category varchar(255), demand_percentage integer not null, demand_source varchar(255), "
                    + "name varchar(255), status varchar(255), primary key (id))");
            statement.execute("insert into skills (name, category, demand_percentage, demand_source, status) values "
                    + "('React', 'Frontend', 95, 'JOB_POSTINGS', 'PENDING'), "
                    + "('SQL', 'Datos', 90, 'SEEDED', 'PENDING'), "
                    + "('Python', 'Datos', 92, null, 'PENDING')");
        }
        registry.add("spring.datasource.url", () -> URL);
    }

    @Test
    void oldSkillsStayAsCatalogAndOwnSkillsCanBeAdded() throws Exception {
        assertThat(jdbc.queryForObject("select count(*) from skills where owner_id is null", Integer.class))
                .isEqualTo(3);

        String token = TestAuth.register(mvc);
        String skills = mvc.perform(get("/api/skills").with(TestAuth.bearer(token)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$", hasSize(3)))
                .andReturn().getResponse().getContentAsString(StandardCharsets.UTF_8);
        List<Boolean> custom = JsonPath.read(skills, "$[*].custom");
        assertThat(custom).containsOnly(false);
        List<String> sources = JsonPath.read(skills, "$[*].demandSource");
        assertThat(sources).doesNotContain("NONE"); // las de antes tienen datos de mercado
        List<Integer> ids = JsonPath.read(skills, "$[*].id");

        mvc.perform(post("/api/goals/custom").with(TestAuth.bearer(token)).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Mixto\",\"skillIds\":[" + ids.get(1) + "],\"newSkills\":[\"Figma\",\"Excel avanzado\"]}"))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.skills", hasSize(3)));
        mvc.perform(get("/api/skills").with(TestAuth.bearer(token))).andExpect(jsonPath("$", hasSize(5)));
        assertThat(jdbc.queryForObject("select count(*) from skills where owner_id is null", Integer.class))
                .isEqualTo(3);
    }
}
