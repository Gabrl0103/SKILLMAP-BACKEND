package com.skillmap.api.presentation.controller;

import com.jayway.jsonpath.JsonPath;
import com.skillmap.api.infrastructure.security.BCryptPasswordHasher;
import com.skillmap.api.support.TestAuth;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Una base de antes del titular (tabla users sin la columna headline, como la de una instalación
 * anterior) sigue funcionando: al arrancar se agrega la columna, la cuenta entra con su contraseña
 * de siempre y queda sin titular hasta que lo edite.
 */
@SpringBootTest(properties = {
        "skillmap.home=${java.io.tmpdir}/skillmap-legacy-users-test",
        "skillmap.desktop.open-browser=false",
        "jobs.sync.on-first-start=false",
        "jobs.sync.cron=-",
        "spring.jpa.show-sql=false",
        "GEMINI_API_KEY="
})
@AutoConfigureMockMvc
class LegacyUsersTableTest {

    private static final String URL = "jdbc:h2:mem:skillmap-legacy-users-test;DB_CLOSE_DELAY=-1";
    private static final String EMAIL = "antigua@test.local";
    private static final String PASSWORD = "Clave-De-Antes-123";

    @Autowired
    MockMvc mvc;

    /** Antes de crear el contexto: la tabla users tal como la dejaba la versión anterior, con una cuenta. */
    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        try (Connection connection = DriverManager.getConnection(URL, "sa", "");
             Statement statement = connection.createStatement()) {
            statement.execute("create table users (id bigint generated by default as identity, "
                    + "created_at timestamp(6) with time zone not null, email varchar(254) not null, "
                    + "name varchar(60) not null, password_hash varchar(100) not null, primary key (id), "
                    + "constraint uk_users_email unique (email))");
            try (PreparedStatement insert = connection.prepareStatement(
                    "insert into users (created_at, email, name, password_hash) values (?, ?, ?, ?)")) {
                insert.setTimestamp(1, Timestamp.from(Instant.parse("2025-01-15T10:00:00Z")));
                insert.setString(2, EMAIL);
                insert.setString(3, "Cuenta Antigua");
                insert.setString(4, new BCryptPasswordHasher().hash(PASSWORD));
                insert.executeUpdate();
            }
        }
        registry.add("spring.datasource.url", () -> URL);
    }

    @Test
    void existingAccountKeepsWorkingWithoutHeadlineAndCanAddOne() throws Exception {
        String response = mvc.perform(post("/api/auth/login").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"" + EMAIL + "\",\"password\":\"" + PASSWORD + "\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.user.name").value("Cuenta Antigua"))
                .andExpect(jsonPath("$.user.headline").isEmpty())
                .andReturn().getResponse().getContentAsString();
        String token = JsonPath.read(response, "$.token");

        mvc.perform(patch("/api/auth/me").with(TestAuth.bearer(token)).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"headline\":\"Cloud Architect\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("Cuenta Antigua"))
                .andExpect(jsonPath("$.headline").value("Cloud Architect"));
        mvc.perform(get("/api/auth/me").with(TestAuth.bearer(token)))
                .andExpect(jsonPath("$.email").value(EMAIL))
                .andExpect(jsonPath("$.headline").value("Cloud Architect"));
    }
}
