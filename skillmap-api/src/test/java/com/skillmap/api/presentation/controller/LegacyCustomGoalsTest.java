package com.skillmap.api.presentation.controller;

import com.jayway.jsonpath.JsonPath;
import com.skillmap.api.infrastructure.security.BCryptPasswordHasher;
import com.skillmap.api.support.TestAuth;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.delete;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Una base de la versión anterior (users con goal_id y sin base_goal_id; sin custom_goals) sigue funcionando: al
 * arrancar se crean las tablas nuevas vacías, la cuenta recibe su objetivo elegido como "base anterior" y no pierde
 * habilidades ni progreso. Después puede crear, elegir y borrar un objetivo propio y vuelve a su objetivo de antes.
 */
@SpringBootTest(properties = {
        "skillmap.home=${java.io.tmpdir}/skillmap-legacy-custom-goals-test",
        "skillmap.desktop.open-browser=false",
        "jobs.sync.on-first-start=false",
        "jobs.sync.cron=-",
        "jobs.remotive.base-url=http://127.0.0.1:9",
        "jobs.arbeitnow.base-url=http://127.0.0.1:9",
        "skillmap.ai.remote-url=http://127.0.0.1:9",
        "skillmap.sync.remotive.enabled=false",
        "skillmap.sync.arbeitnow.enabled=false",
        "spring.jpa.show-sql=false",
        "GEMINI_API_KEY="
})
@AutoConfigureMockMvc
class LegacyCustomGoalsTest {

    private static final String URL = "jdbc:h2:mem:skillmap-legacy-custom-goals-test;DB_CLOSE_DELAY=-1";
    private static final String EMAIL = "cuenta-de-antes@test.local";
    private static final String PASSWORD = "Clave-De-Antes-123";

    @Autowired
    MockMvc mvc;

    @Autowired
    JdbcTemplate jdbc;

    /** users y user_skills como las dejaba la versión anterior: objetivo 2 elegido, React dominada y TypeScript en curso. */
    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        try (Connection connection = DriverManager.getConnection(URL, "sa", "");
             Statement statement = connection.createStatement()) {
            statement.execute("create table users (id bigint generated by default as identity, "
                    + "created_at timestamp(6) with time zone not null, email varchar(254) not null, "
                    + "name varchar(60) not null, password_hash varchar(100) not null, headline varchar(160), "
                    + "goal_id bigint, primary key (id), constraint uk_users_email unique (email))");
            statement.execute("create table user_skills (id bigint generated by default as identity, "
                    + "skill_id bigint not null, status varchar(255) not null, user_id bigint not null, "
                    + "updated_at timestamp(6) with time zone, primary key (id), "
                    + "constraint uk_user_skills_user_skill unique (user_id, skill_id))");
            try (PreparedStatement insert = connection.prepareStatement(
                    "insert into users (created_at, email, name, password_hash, goal_id) values (?, ?, ?, ?, 2)")) {
                insert.setTimestamp(1, Timestamp.from(Instant.parse("2025-06-01T10:00:00Z")));
                insert.setString(2, EMAIL);
                insert.setString(3, "Cuenta de antes");
                insert.setString(4, new BCryptPasswordHasher().hash(PASSWORD));
                insert.executeUpdate();
            }
            statement.execute("insert into user_skills (user_id, skill_id, status, updated_at) values "
                    + "((select id from users where email = '" + EMAIL + "'), 1, 'MASTERED', current_timestamp), "
                    + "((select id from users where email = '" + EMAIL + "'), 2, 'IN_PROGRESS', current_timestamp)");
        }
        registry.add("spring.datasource.url", () -> URL);
    }

    @Test
    void existingAccountKeepsItsProgressAndCanUseCustomGoals() throws Exception {
        assertThat(jdbc.queryForObject("select base_goal_id from users where email = ?", Long.class, EMAIL))
                .isEqualTo(2L);
        assertThat(jdbc.queryForObject("select count(*) from custom_goals", Long.class)).isZero();

        String login = mvc.perform(post("/api/auth/login").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"email\":\"" + EMAIL + "\",\"password\":\"" + PASSWORD + "\"}"))
                .andExpect(status().isOk()).andReturn().getResponse().getContentAsString();
        String token = JsonPath.read(login, "$.token");
        mvc.perform(get("/api/auth/me").with(TestAuth.bearer(token))).andExpect(jsonPath("$.goalId").value(2));
        mvc.perform(get("/api/skills/1").with(TestAuth.bearer(token))).andExpect(jsonPath("$.status").value("MASTERED"));
        mvc.perform(get("/api/skills/2").with(TestAuth.bearer(token)))
                .andExpect(jsonPath("$.status").value("IN_PROGRESS"));

        String created = mvc.perform(post("/api/goals/custom").with(TestAuth.bearer(token))
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Mi rol\",\"skillIds\":[1,2,3]}"))
                .andExpect(status().isCreated()).andReturn().getResponse().getContentAsString();
        long id = ((Number) JsonPath.read(created, "$.id")).longValue();
        mvc.perform(put("/api/auth/me/goal").with(TestAuth.bearer(token)).contentType(MediaType.APPLICATION_JSON)
                .content("{\"goalId\":" + id + "}")).andExpect(status().isOk());
        mvc.perform(get("/api/goals/" + id + "/readiness").with(TestAuth.bearer(token)))
                .andExpect(jsonPath("$.readinessPercentage").value(33)) // React dominada: 1 de 3
                .andExpect(jsonPath("$.masteredCount").value(1));

        mvc.perform(delete("/api/goals/custom/" + id).with(TestAuth.bearer(token)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.goalId").value(2));
        List<String> statuses = jdbc.queryForList("select status from user_skills order by skill_id", String.class);
        assertThat(statuses).containsExactly("MASTERED", "IN_PROGRESS");
    }
}
