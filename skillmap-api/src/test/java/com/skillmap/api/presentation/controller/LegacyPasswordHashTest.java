package com.skillmap.api.presentation.controller;

import com.jayway.jsonpath.JsonPath;
import com.skillmap.api.support.TestAuth;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.request.MockHttpServletRequestBuilder;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Migración de contraseñas: una base de la versión 1.0 (BCrypt costo 10, correo guardado con mayúsculas, nombre y
 * contraseña que hoy no pasarían las reglas nuevas) sigue entrando. En el primer login correcto el hash se rehace con
 * costo 12, sin pedir nada; los datos de la cuenta no cambian. Un login fallido no toca el hash.
 */
@SpringBootTest(properties = {
        "skillmap.home=${java.io.tmpdir}/skillmap-legacy-hash-test",
        "skillmap.desktop.open-browser=false",
        "jobs.sync.on-first-start=false",
        "jobs.sync.cron=-",
        "spring.jpa.show-sql=false",
        "GEMINI_API_KEY="
})
@AutoConfigureMockMvc
class LegacyPasswordHashTest {

    private static final String URL = "jdbc:h2:mem:skillmap-legacy-hash-test;DB_CLOSE_DELAY=-1";
    /** Contraseña sin número (hoy no se aceptaría al registrarse) y nombre con dígitos y emoji (tampoco). */
    private static final String OLD_PASSWORD = "contrasenaantigua";
    private static final String OTHER_PASSWORD = "otraclaveantigua";

    @Autowired
    MockMvc mvc;

    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        BCryptPasswordEncoder version10 = new BCryptPasswordEncoder(); // costo 10, como guardaba la versión 1.0
        try (Connection connection = DriverManager.getConnection(URL, "sa", "");
             Statement statement = connection.createStatement()) {
            statement.execute("create table users (id bigint generated by default as identity, "
                    + "created_at timestamp(6) with time zone not null, email varchar(254) not null, "
                    + "name varchar(60) not null, password_hash varchar(100) not null, headline varchar(160), "
                    + "goal_id bigint, primary key (id), constraint uk_users_email unique (email))");
            try (PreparedStatement insert = connection.prepareStatement(
                    "insert into users (created_at, email, name, password_hash) values (?, ?, ?, ?)")) {
                insert.setTimestamp(1, Timestamp.from(Instant.parse("2025-03-01T10:00:00Z")));
                insert.setString(2, "antigua@test.local");
                insert.setString(3, "Ana 2025 😀");
                insert.setString(4, version10.encode(OLD_PASSWORD));
                insert.executeUpdate();
                insert.setString(2, "Mayusculas@Test.Local");
                insert.setString(3, "Otra");
                insert.setString(4, version10.encode(OTHER_PASSWORD));
                insert.executeUpdate();
            }
        }
        registry.add("spring.datasource.url", () -> URL);
    }

    @Test
    void oldAccountLogsInAndItsHashIsUpgradedToCost12() throws Exception {
        String before = storedHash("antigua@test.local");
        assertThat(before).startsWith("$2a$10$");

        // Un fallo no toca el hash.
        mvc.perform(login("antigua@test.local", "no-es-la-clave")).andExpect(status().isUnauthorized());
        assertThat(storedHash("antigua@test.local")).isEqualTo(before);

        String token = JsonPath.read(mvc.perform(login("antigua@test.local", OLD_PASSWORD))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.user.name").value("Ana 2025 😀"))
                .andReturn().getResponse().getContentAsString(), "$.token");

        String after = storedHash("antigua@test.local");
        assertThat(after).startsWith("$2a$12$").isNotEqualTo(before);

        // La misma contraseña sigue valiendo con el hash nuevo, y la sesión funciona.
        mvc.perform(login("antigua@test.local", OLD_PASSWORD)).andExpect(status().isOk());
        assertThat(storedHash("antigua@test.local")).isEqualTo(after); // ya no se rehace
        mvc.perform(get("/api/auth/me").with(TestAuth.bearer(token)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.email").value("antigua@test.local"));

        // Puede editar su titular aunque su nombre no pasaría las reglas de hoy (no lo cambia).
        mvc.perform(patch("/api/auth/me").with(TestAuth.bearer(token)).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Ana 2025 😀\",\"headline\":\"Backend\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.headline").value("Backend"));
    }

    @Test
    void oldAccountSavedWithUppercaseEmailIsFoundIgnoringCase() throws Exception {
        mvc.perform(login("mayusculas@test.local", OTHER_PASSWORD)).andExpect(status().isOk());
        assertThat(storedHash("Mayusculas@Test.Local")).startsWith("$2a$12$");
        // Y no se puede registrar otra cuenta con el mismo correo en minúsculas.
        mvc.perform(post("/api/auth/register").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"name\":\"Copia\",\"email\":\"mayusculas@test.local\",\"password\":\"Nueva-Clave-123\"}"))
                .andExpect(status().isConflict());
    }

    private static MockHttpServletRequestBuilder login(String email, String password) {
        return post("/api/auth/login").contentType(MediaType.APPLICATION_JSON)
                .content("{\"email\":\"" + email + "\",\"password\":\"" + password + "\"}");
    }

    private static String storedHash(String email) throws Exception {
        try (Connection connection = DriverManager.getConnection(URL, "sa", "");
             PreparedStatement select = connection.prepareStatement("select password_hash from users where email = ?")) {
            select.setString(1, email);
            try (ResultSet rows = select.executeQuery()) {
                assertThat(rows.next()).isTrue();
                return rows.getString(1);
            }
        }
    }
}
